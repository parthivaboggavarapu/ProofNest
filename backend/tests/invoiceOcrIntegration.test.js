const path = require('path');
const dotenv = require('dotenv');
dotenv.config({ path: path.resolve(__dirname, '../.env') });
dotenv.config();

const mongoose = require('mongoose');
const app = require('../src/app');
const { connectDB, disconnectDB, getGridFSBucket } = require('../src/config/db');
const n8nService = require('../src/services/n8nService');
const { User, Document, Product, ProcessingJob } = require('../src/models');
const { generateAccessToken } = require('../src/utils/tokenUtils');
const axios = require('axios');

async function runInvoiceOcrTests() {
  console.log('\n===================================================================');
  console.log('  ProofNest: Invoice OCR Integration & Backend Contract Tests');
  console.log('===================================================================\n');

  let passed = 0;
  let failed = 0;

  function assert(condition, message) {
    if (condition) {
      console.log(`  [PASS] ${message}`);
      passed++;
    } else {
      console.error(`  [FAIL] ${message}`);
      failed++;
    }
  }

  const TEST_PORT = 5059;
  let server;
  let testUser;
  let userToken;
  let testDoc;

  try {
    await connectDB();
    server = app.listen(TEST_PORT);
    const baseUrl = `http://localhost:${TEST_PORT}`;
    const webhookSecret = process.env.N8N_WEBHOOK_SECRET || 'n8n_test_shared_secret';
    process.env.N8N_WEBHOOK_SECRET = webhookSecret;

    // 1. Setup authenticated test user
    console.log('[1/6] Setting up authenticated user and JWT session...');
    testUser = await User.create({
      name: 'Invoice OCR Tester',
      email: `ocr_test_${Date.now()}@example.com`,
      passwordHash: 'dummy_hash_for_testing'
    });
    userToken = generateAccessToken(testUser);
    assert(typeof userToken === 'string', 'Generated JWT access token for authenticated API requests');

    // 2. Upload Invoice Document to GridFS
    console.log('\n[2/6] Validating file storage in GridFS and Document creation...');
    const bucket = getGridFSBucket();
    const uploadStream = bucket.openUploadStream('bestbuy_invoice.pdf', {
      contentType: 'application/pdf',
      metadata: { userId: testUser._id.toString() }
    });
    uploadStream.end(Buffer.from('%PDF-1.4 Mock Invoice Content for Apple MacBook Pro 16 M3 Max'));
    await new Promise(resolve => uploadStream.on('finish', resolve));

    testDoc = await Document.create({
      userId: testUser._id,
      originalFileName: 'bestbuy_invoice.pdf',
      mimeType: 'application/pdf',
      fileSize: 64,
      documentType: 'Invoice',
      gridFsFileId: uploadStream.id
    });
    assert(testDoc._id && testDoc.gridFsFileId.equals(uploadStream.id), 'Invoice file stored in GridFS and Document record created');

    // 3. Trigger n8n Invoice OCR through authenticated endpoint
    console.log('\n[3/6] Triggering Invoice OCR processing via POST /api/integrations/n8n/document-processing...');
    const triggerRes = await axios.post(
      `${baseUrl}/api/integrations/n8n/document-processing`,
      { documentId: testDoc._id.toString() },
      { headers: { Authorization: `Bearer ${userToken}` } }
    );
    assert(triggerRes.status === 202 && triggerRes.data.success === true, 'Express accepted request with HTTP 202');
    
    const { jobId, status } = triggerRes.data.data;
    assert(typeof jobId === 'string' && jobId.startsWith('job_ocr_'), `Created ProcessingJob with ID: ${jobId}`);
    assert(status === 'pending' || status === 'processing', `Initial job status is: ${status}`);

    // Verify webhook payload contract generated by n8nService
    const jobRecord = await ProcessingJob.findOne({ jobId });
    assert(jobRecord && jobRecord.userId.equals(testUser._id), 'ProcessingJob linked strictly to authenticated user');

    // 4. Verify secure, short-lived download endpoint for n8n
    console.log('\n[4/6] Verifying short-lived scoped document retrieval for n8n...');
    const { generateDocumentAccessToken } = require('../src/middleware/n8nAuthMiddleware');
    const validToken = generateDocumentAccessToken(testDoc._id, 60);

    const downloadRes = await axios.get(
      `${baseUrl}/api/integrations/n8n/documents/${testDoc._id}/download?token=${validToken}`,
      { responseType: 'arraybuffer' }
    );
    assert(downloadRes.status === 200, 'n8n worker successfully downloaded invoice via scoped token');

    try {
      await axios.get(`${baseUrl}/api/integrations/n8n/documents/${testDoc._id}/download?token=invalid_token`);
      assert(false, 'Should have failed with invalid token');
    } catch (err) {
      assert(err.response?.status === 403, 'Unauthorized download correctly rejected with HTTP 403');
    }

    // 5. Authenticated Callback with Extracted Invoice Fields
    console.log('\n[5/6] Sending OCR callback to POST /api/integrations/n8n/document-processing/callback...');
    const extractedPayload = {
      productName: 'MacBook Pro 16-inch',
      brand: 'Apple',
      modelNumber: 'A2991',
      purchaseDate: '2026-03-15',
      purchasePrice: 2499.00,
      seller: 'Best Buy Store #102',
      invoiceNumber: 'INV-BB-889911',
      warrantyExpiry: '2027-03-15',
      serialNumber: 'C02G41KSMD6R'
    };

    const callbackRes = await axios.post(
      `${baseUrl}/api/integrations/n8n/document-processing/callback`,
      {
        jobId,
        status: 'completed',
        extractedData: extractedPayload,
        rawText: 'Best Buy Tax Invoice #INV-BB-889911 Apple MacBook Pro 16-inch $2499.00'
      },
      { headers: { 'X-ProofNest-Webhook-Secret': webhookSecret } }
    );
    assert(callbackRes.status === 200 && callbackRes.data.success === true, 'Callback authenticated and processed');

    // Verify job status and pending result awaiting user confirmation
    const pollRes = await axios.get(
      `${baseUrl}/api/integrations/n8n/jobs/${jobId}`,
      { headers: { Authorization: `Bearer ${userToken}` } }
    );
    assert(pollRes.data.data.status === 'completed', 'Frontend poll reflects status: completed');
    assert(
      pollRes.data.data.result.extractedData.productName === 'MacBook Pro 16-inch' &&
      pollRes.data.data.result.extractedData.brand === 'Apple' &&
      pollRes.data.data.result.extractedData.purchasePrice === 2499 &&
      pollRes.data.data.result.extractedData.invoiceNumber === 'INV-BB-889911' &&
      pollRes.data.data.result.awaitingUserConfirmation === true,
      'Extracted fields accurately sanitized and stored as pending confirmation'
    );

    // Verify Product record was NOT updated prematurely without confirmation
    const preConfirmProducts = await Product.find({ userId: testUser._id });
    assert(preConfirmProducts.length === 0, 'No Product created automatically before user confirmation');

    // 6. User Review & Confirmation Flow
    console.log('\n[6/6] Confirming OCR results via POST /api/integrations/n8n/confirm-ocr...');
    const userAdjustedData = {
      ...pollRes.data.data.result.extractedData,
      notes: 'Purchased with AppleCare Protection'
    };

    const confirmRes = await axios.post(
      `${baseUrl}/api/integrations/n8n/confirm-ocr`,
      {
        jobId,
        confirmedProductData: userAdjustedData
      },
      { headers: { Authorization: `Bearer ${userToken}` } }
    );
    assert(confirmRes.status === 200 && confirmRes.data.success === true, 'Product created upon explicit user confirmation');
    
    const createdProduct = confirmRes.data.data.product;
    assert(
      createdProduct.productName === 'MacBook Pro 16-inch' &&
      createdProduct.purchasePrice === 2499 &&
      createdProduct.serialNumber === 'C02G41KSMD6R',
      'Confirmed product attributes persisted in MongoDB Atlas Product collection'
    );

    const updatedDoc = await Document.findById(testDoc._id);
    assert(updatedDoc.productId.equals(createdProduct._id), 'Document linked to newly confirmed Product record');

    // Clean up test files
    await bucket.delete(uploadStream.id);

    console.log('\n===================================================================');
    console.log(`  Invoice OCR Test Suite Complete: ${passed} Passed, ${failed} Failed`);
    console.log('===================================================================\n');

  } catch (err) {
    console.error('Invoice OCR tests encountered an error:', err.response?.data || err.message);
    failed++;
  } finally {
    if (testUser) {
      await ProcessingJob.deleteMany({ userId: testUser._id });
      await Document.deleteMany({ userId: testUser._id });
      await Product.deleteMany({ userId: testUser._id });
      await User.findByIdAndDelete(testUser._id);
    }
    if (server) {
      await new Promise(r => server.close(r));
    }
    await disconnectDB();
  }

  process.exit(failed > 0 ? 1 : 0);
}

runInvoiceOcrTests();
